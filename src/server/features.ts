/**
 * Διακόπτες λειτουργιών του καταστήματος.
 *
 * Παραγγελίες πελάτη από το κινητό (QR): ΚΛΕΙΣΤΕΣ μέχρι να συνδεθεί online πληρωμή.
 * Με κλειστό το QR: η σελίδα /order δείχνει μόνο το μενού («παράγγειλε στο ταμείο»), ο server αρνείται κάθε παραγγελία,
 * τα ταμεία δεν διαλέγουν χώρους QR και η Διαχείριση δεν τυπώνει QR παραγγελίας. Ενεργοποίηση: NIDO_QR_ORDERING=1.
 */
export function qrOrderingEnabled(): boolean {
  return process.env.NIDO_QR_ORDERING === "1";
}

export const QR_ORDERING_OFF_MESSAGE = "Οι παραγγελίες από το κινητό δεν είναι διαθέσιμες. Παράγγειλε στο ταμείο.";
